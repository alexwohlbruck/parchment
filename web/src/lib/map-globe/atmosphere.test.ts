import { describe, expect, it } from 'vitest'
import sharp from 'sharp'
import { atmosphericTransmission, buildTransmittanceLookup, TRANSMITTANCE_WIDTH, TRANSMITTANCE_HEIGHT } from './atmosphere'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

describe('atmospheric sunlight transmission', () => {
  it('matches the clear-air zenith optical depth and preferentially scatters blue', () => {
    const [red, green, blue] = atmosphericTransmission(0, 1)
    expect(red).toBeGreaterThan(0.93)
    expect(red).toBeLessThan(0.95)
    expect(green).toBeGreaterThan(0.85)
    expect(green).toBeLessThan(0.89)
    expect(blue).toBeGreaterThan(0.75)
    expect(blue).toBeLessThan(0.78)
  })

  it('turns grazing sunlight red as its air path grows longer', () => {
    const vertical = atmosphericTransmission(0, 1)
    const horizon = atmosphericTransmission(0, 0)
    expect(horizon[0]).toBeGreaterThan(horizon[1] * 5)
    expect(horizon[1]).toBeGreaterThan(horizon[2] * 5)
    horizon.forEach((value, channel) => expect(value).toBeLessThan(vertical[channel]))
  })

  it('puts the surface in Earth’s shadow while the upper atmosphere remains sunlit', () => {
    expect(atmosphericTransmission(0, -0.05)).toEqual([0, 0, 0])
    atmosphericTransmission(60_000, -0.05).forEach(value => expect(value).toBeGreaterThan(0.97))
  })

  it('thins with altitude and becomes transparent at the top of the shell', () => {
    const ground = atmosphericTransmission(0, 1)
    atmosphericTransmission(30_000, 1).forEach((value, channel) => expect(value).toBeGreaterThan(ground[channel]))
    atmosphericTransmission(100_000, 1).forEach(value => expect(value).toBeCloseTo(1, 6))
  })

  it('keeps oblique and boundary rays finite and within physical transmission limits', () => {
    for (const height of [0, 100, 8000, 25_000, 80_000, 100_000]) {
      for (const cosine of [-1, -0.2, -0.01, 0, 0.01, 0.2, 1]) {
        for (const value of atmosphericTransmission(height, cosine)) {
          expect(Number.isFinite(value)).toBe(true)
          expect(value).toBeGreaterThanOrEqual(0)
          expect(value).toBeLessThanOrEqual(1)
        }
      }
    }
  })

  it('ships exactly the lookup generated by the tested atmosphere model', async () => {
    const path = resolve(dirname(fileURLToPath(import.meta.url)), '../../assets/map-globe/transmittance.png')
    const { data, info } = await sharp(path).raw().toBuffer({ resolveWithObject: true })
    expect(info.width).toBe(TRANSMITTANCE_WIDTH)
    expect(info.height).toBe(TRANSMITTANCE_HEIGHT)
    expect(Buffer.from(buildTransmittanceLookup()).equals(data)).toBe(true)
  })
})
